/**
 * Versioned 27-action catalog (v1).
 *
 * Agents see action id, target requirement, phase-neutral description and
 * constraints. Severity labels and score weights are metadata for the engine
 * and analytics layer ONLY (hidden from agents in the baseline condition).
 *
 * All numeric effects are SYNTHETIC RESEARCH PARAMETERS with no real-world
 * counterpart. No action models real operational procedures.
 */
import type { ActionCatalog, CatalogEntry, Effect, Precondition } from '@aiww/schemas';

const v = 1;

function entry(e: Omit<CatalogEntry, 'version'>): CatalogEntry {
  return { ...e, version: v };
}

const vd = (scope: 'self' | 'other', variable: import('@aiww/schemas').VariableName, delta: number, deterrenceMitigatable = false): Effect =>
  ({ kind: 'var_delta', scope, variable, delta, ...(deterrenceMitigatable ? { deterrenceMitigatable: true } : {}) });

const rel = (dimension: 'affinity' | 'tension' | 'trust' | 'tradeRelationship', scope: 'pair' | 'third_parties', delta: number): Effect =>
  ({ kind: 'rel_delta', dimension, scope, delta });

